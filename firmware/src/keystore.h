// Known-key dictionary + per-card found keys saved in NVS (flash). On a re-tap the
// stored keys are tried first, so a known card reads instantly and clones carry keys.
#pragma once
#include <Arduino.h>
#include <Preferences.h>

struct SectorKey {
  uint8_t a[6] = {0, 0, 0, 0, 0, 0};
  uint8_t b[6] = {0, 0, 0, 0, 0, 0};
  bool haveA = false, haveB = false;
};

